const assert = require('node:assert/strict');
module.exports = async function checkCustomRecords(page) {
  await page.evaluate(() => applyState({ fields: { 'char-name': 'Custom Records' }, classes: [] }));
  await page.locator('#custom-item-add').click();
  const item = page.locator('#custom-item-editor');
  await item.locator('[name="name"]').fill('Custom <item>');
  await item.locator('[name="qty"]').fill('2');
  await item.locator('[name="weight"]').fill('3.5');
  await item.locator('[name="value"]').fill('25');
  await item.locator('[name="description"]').fill('Homebrew description <script>bad()</script>');
  await item.locator('[name="rarity"]').selectOption('rare');
  await item.locator('[name="attunement"]').check();
  await item.locator('[type="submit"]').click();
  assert.equal(await page.locator('#items-weight-total').innerText(), '7');
  assert.equal(await page.locator('#items-value-total').innerText(), '50');
  await page.evaluate(() => {
    ITEM_LIB.push({ name: 'Custom <item>', source: 'Test', weight: 99, valueGp: 999, spells: ['Library-only spell'] });
    CHARACTER_ITEMS[0].eq = true;
    if (equippedArmorLibs()[0].source !== 'Custom' || resolvedItem(CHARACTER_ITEMS[0]).wt !== 3.5) throw new Error('Custom item inherited library stats');
    if (derivedSpellGroups().some(group => group.names.includes('Library-only spell'))) throw new Error('Custom item inherited library spells');
    ITEM_LIB.pop(); CHARACTER_ITEMS[0].eq = false;
  });
  await page.locator('#char-item-list .inv-link').click();
  assert.match(await page.locator('#char-item-list .feat-detail').innerText(), /Homebrew description/);
  assert.match(await page.locator('#char-item-list .feat-detail').innerText(), /rare/);
  assert.equal(await page.locator('#char-item-list script').count(), 0);
  await page.locator('[data-custom-item-edit]').click();
  assert.equal(await item.locator('[name="rarity"]').inputValue(), 'rare');
  await item.locator('[name="rarity"]').selectOption('very rare');
  await item.locator('[name="value"]').fill('30');
  await item.locator('[type="submit"]').click();
  assert.equal(await page.locator('#items-value-total').innerText(), '60');
  await page.locator('#custom-creature-add').click();
  const creature = page.locator('#custom-creature-editor');
  await creature.locator('[name="name"]').fill('Clockwork Cat');
  await creature.locator('[name="ac"]').fill('15');
  await creature.locator('[name="hp"]').fill('22');
  await creature.locator('[name="dex"]').fill('16');
  await creature.locator('[name="saves"]').fill('dex +5');
  await creature.locator('[name="skills"]').fill('perception +4');
  await creature.locator('[data-custom-action-add]').click();
  await creature.locator('[name="action-name"]').fill('Claw');
  await creature.locator('[name="action-hit"]').fill('+5');
  await creature.locator('[name="action-damage"]').fill('1d6+3');
  await creature.locator('[name="action-description"]').fill('A sharp mechanical claw.');
  await creature.locator('[data-custom-action-add]').click();
  const trait = creature.locator('.custom-action-row').nth(1);
  await trait.locator('[name="action-kind"]').selectOption('trait');
  await trait.locator('[name="action-name"]').fill('Loyal');
  await trait.locator('[name="action-description"]').fill('Follows its creator.');
  await creature.locator('[type="submit"]').click();
  assert.equal(await page.locator('#companions-list .cmp-hp').inputValue(), '22');
  assert.match(await page.locator('#companions-list').innerText(), /AC 15/);
  assert.equal(await page.locator('#companions-list [data-attack="true"]').getAttribute('data-bonus'), '5');
  assert.equal(await page.locator('#companions-list .cmp-dmg').getAttribute('data-expr'), '1d6+3');
  await page.locator('#companions-list .cmp-link').click();
  assert.match(await page.locator('#companions-list .feat-detail').innerText(), /Follows its creator/);
  await page.locator('[data-custom-creature-edit]').click();
  await creature.locator('[name="name"]').fill('Revised Clockwork Cat');
  assert.equal(await creature.locator('[name="action-damage"]').first().inputValue(), '1d6+3');
  await creature.locator('[type="submit"]').click();
  await page.reload();
  await page.waitForFunction(() => CHARACTER_ITEMS.some(it => it.custom) && COMPANIONS.some(c => c.customRaw));
  assert.equal(await page.locator('#items-value-total').innerText(), '60');
  assert.match(await page.locator('#companions-list').innerText(), /Revised Clockwork Cat/);
  assert.equal(await page.evaluate(() => CHARACTER_ITEMS[0].custom.rarity), 'very rare');
  await page.evaluate(() => {
    const saved = JSON.stringify(collectState());
    applyState({ fields: {}, classes: [] });
    if (CHARACTER_ITEMS.length || COMPANIONS.length) throw new Error('Custom records leaked across characters');
    importCharacterState(saved);
    if (!CHARACTER_ITEMS[0].custom || !COMPANIONS[0].customRaw) throw new Error('Custom records not exported');
  });
  await page.locator('[data-custom-item-edit]').click();
  await page.locator('#char-item-list .inv-del').click();
  assert(await item.isHidden());
  await page.locator('[data-custom-creature-edit]').click();
  await page.locator('#companions-list .cmp-del').click();
  assert(await creature.isHidden());
  assert.equal(await page.locator('#items-value-total').innerText(), '0');
  console.log('Custom records: items with weight/value/attunement, stat blocks with HP/AC/saves/traits/rollable attacks, editing, removal, reload and export/import passed.');
};
